-- ADR-048 (authentication hardening, Phase S4): optional TOTP two-step verification, for administrators.
-- mfa_secret holds the authenticator secret ENCRYPTED (AES-256-GCM, Base64), never the plain secret.
-- mfa_last_step is the newest 30-second time step whose code was accepted: a code for that step or an older one is
-- refused, so a code cannot be used twice. Recovery codes are stored as BCrypt hashes and each works once.
-- V7 and V8 stay reserved (decision D21), V9 to V12 are taken: this is V13.
ALTER TABLE users ADD COLUMN mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN mfa_secret VARCHAR(255);
ALTER TABLE users ADD COLUMN mfa_last_step BIGINT;

CREATE TABLE mfa_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code_hash VARCHAR(100) NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- a sign-in with a recovery code reads the user's unused codes
CREATE INDEX idx_mfa_recovery_codes_user ON mfa_recovery_codes(user_id);
