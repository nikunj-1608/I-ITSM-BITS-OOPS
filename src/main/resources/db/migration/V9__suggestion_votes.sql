-- ADR-041 (suggested resolutions, Phase K2): a technician's verdict on a suggested fix.
-- One row per (voter, source, target ticket); voting again updates the row. V7 and V8 stay reserved for the
-- conditional migrations of decision D21 (remaining-defects plan), so this is V9.
-- source_id has no foreign key: a source is a resolved ticket or (from V10) a knowledge-base article.
CREATE TABLE suggestion_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voter_id VARCHAR(64) NOT NULL REFERENCES users(id),
    source_type VARCHAR(16) NOT NULL,
    source_id VARCHAR(64) NOT NULL,
    target_incident_id VARCHAR(64) NOT NULL REFERENCES incidents(id) ON DELETE CASCADE ON UPDATE CASCADE,
    worked BOOLEAN NOT NULL,
    voted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_suggestion_votes_voter_source_target UNIQUE (voter_id, source_type, source_id, target_incident_id),
    CONSTRAINT ck_suggestion_votes_source_type CHECK (source_type IN ('RESOLVED_TICKET', 'KB_ARTICLE'))
);

-- The ranking reads the vote counts of up to candidate-window sources per request.
CREATE INDEX idx_suggestion_votes_source ON suggestion_votes(source_type, source_id);
