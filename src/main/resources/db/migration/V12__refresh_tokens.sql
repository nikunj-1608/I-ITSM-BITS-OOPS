-- ADR-047 (authentication hardening, Phase S3): refresh tokens of a session.
-- Only the SHA-256 hash (64 hex characters) of a token is stored, never the token. The tokens of one sign-in share a
-- family_id (the sid claim of its access tokens); each refresh revokes the presented token as ROTATED and adds the
-- next one. V7 and V8 stay reserved for the conditional migrations of decision D21, V9 to V11 are taken: this is V12.
-- replaced_by_id has no foreign key on purpose: purging expired rows must not depend on the order of deletion.
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    family_id VARCHAR(64) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    token_version INT NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_reason VARCHAR(32),
    replaced_by_id BIGINT
);

-- every authenticated request asks whether its session family is alive; sign-in trims a user's sessions;
-- the cleanup scheduler deletes by expiry
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens(user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens(family_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens(expires_at);
